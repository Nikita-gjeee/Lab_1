# test_integration.py
import logic
import menu

def test_full_add_cycle():
    """Интеграционный тест: имитируем добавление записи через меню и проверяем в логике."""
    # 1. Очищаем список
    logic.notes.clear()
    
    # 2. Имитируем то, что делает пользователь через меню (выбор пункта "1" и ввод текста)
    # Мы не можем нажать кнопку, поэтому просто вызываем функции напрямую
    text = "Интеграционная запись"
    logic.add_note(text) 
    
    # 3. Проверяем, что запись действительно появилась
    assert len(logic.get_notes()) == 1
    assert logic.get_notes()[0] == "Интеграционная запись"